% Create output ensemble.
outputEnsemble = workspaceEnsemble(inputData,'DataVariables',FEATURES, ...
    'IndependentVariables',INDEPENDENT_VARIABLES, ...
    'ConditionVariables',CONDITION_VARIABLES);


% Gather all features into a table.
